PLAN_LINES, COMING_UP, MISTAKES_SHOWN, MOVED_SHOWN, NEXT_SHOWN = 8, 3, 3, 6, 3
CHANGED_SHOWN = 15
HOME_SHOWN, FOLLOW_UPS_SHOWN, DUE_SLICE = 3, 2, CAP  # home card caps (UX-7, COACH-3, COACH-6)
NO_CONCEPT = "▫"
CUE_KINDS, CUE_CHARS = ("confident_miss", "warmup", "refresh"), 140  # Today.md past-question cue
TODAY_HEADER = "<!-- generated by keepfold; safe to delete -->"
INDEX_HEADER = TODAY_HEADER

_URL_PART = r"\((?:[^()]|\([^()]*\))*\)"  # one level of balanced parens: (http://x/(y))
_IMAGE_RE = re.compile(r"!\[[^\]]*\]" + _URL_PART)
_LINK_RE = re.compile(r"\[([^\]]*)\]" + _URL_PART)
# C0/C1 controls (terminal escape sequences, NUL) and bidi overrides that reorder a line
_CTRL_RE = re.compile("[\x00-\x08\x0b-\x1f\x7f-\x9f‪-‮⁦-⁩]")
_WIKI_RE = re.compile(r"\[\[([^\]|]*)(?:\|([^\]]*))?\]\]")
_TAG_RE = re.compile(r"<[^>]*>")
_URL_RE = re.compile(r"(?:https?://|www\.)\S*", re.I)
_MD_CHARS = re.compile(r"([\\`*_\[\]#|~])")


def term(text) -> str:
    """Untrusted text for a terminal: control and bidi characters dropped, newline and tab
    kept. The CLI prints note titles, chat lines and model answers through this."""
    return _CTRL_RE.sub("", str(text))


def plain(text: str, limit: int = 120) -> str:
    """Untrusted note text as one line with images, links, URLs, HTML tags, control and bidi
    characters stripped."""
    s = _IMAGE_RE.sub("", term(text or ""))
    s = _LINK_RE.sub(r"\1", s)
    s = _WIKI_RE.sub(lambda m: m.group(2) or m.group(1), s)
    s = _TAG_RE.sub("", s)
    s = _URL_RE.sub("", s)
    s = " ".join(s.replace("](", "] (").split())
    if len(s) > limit:
        s = s[: limit - 1].rstrip() + "…"
    return s


def esc(text: str, limit: int = 120) -> str:
    """Make untrusted note text safe for Markdown: no images, links, URLs, HTML or markup."""
    s = _MD_CHARS.sub(r"\\\1", plain(text, limit))
    # entities, not backslashes, so no "<" survives for HTML-aware renderers
    return s.replace("<", "&lt;").replace(">", "&gt;")


def brief_text(brief_md: str, budget_tokens: int = 1500) -> str:
    """BRIEF.md capped at budget_tokens (chars/4), cut at a line boundary."""
    cap = budget_tokens * 4
    if len(brief_md) <= cap:
        return brief_md
    marker = "[brief truncated]"
    cut = brief_md[: cap - len(marker) - 1]
    nl = cut.rfind("\n")
    return (cut[:nl] if nl > 0 else cut).rstrip() + "\n" + marker


def _glyph(item: Mapping) -> str:
    return GLYPH.get(item.get("state"), NO_CONCEPT)


def _label(a: Mapping) -> str:
    company, kind = str(a.get("company") or ""), str(a.get("kind") or "")
    if kind.lower() in company.lower().split():  # "Practice OA" + "oa" says OA once
        kind = ""
    return f"{company} {kind}".strip() or a.get("id", "")


def _assessment(a: Mapping) -> str:
    what = esc(_label(a))
    return f"{what} · {esc(a.get('date') or '') or 'date not set'}"


def _pending(assessments: list[dict]) -> list[dict]:
    """Pending, non-private assessments: a private one's company and date never reach Claude."""
    return [a for a in assessments
            if (a.get("outcome") or "pending") == "pending" and not a.get("private")]


def _deadline(d: Mapping) -> str:
    n = d["days"]
    left = "due today" if n == 0 else "1 day left" if n == 1 else f"{n} days left"
    return f"{esc(d['title'])}: {left}"


def _coming(assessments: list[dict], deadlines: list[dict]) -> list[str]:
    """Coming up: pending assessments and plan deadlines by date, undated tests last."""
    rows = [(a.get("date") or "~", _assessment(a)) for a in _pending(assessments)] + [
        (d["date"], _deadline(d)) for d in deadlines]
    return [text for _, text in sorted(rows, key=lambda r: r[0])]


def _unchecked_titles(today: list[dict]) -> list[str]:
    return [esc(i["title"]) for i in today if i.get("kind") == "unchecked"]


def _few(items, sep: str = " · ", n: int = HOME_SHOWN, more: str = " more") -> str:
    """At most n items (escaped here) and "+N more"."""
    items = list(items)
    tail = f" +{len(items) - n}{more}" if len(items) > n else ""
    return sep.join(esc(x) for x in items[:n]) + tail


def _when(days: int) -> str:
    return "today" if days == 0 else "tomorrow" if days == 1 else f"in {days} days"


def home_card(*, domains: list[tuple], due: list[str], open_mistakes: int,
              projects: list[str] = (), loops: list[str] = (), ideas: list[str] = (),
              coming_up: Mapping | None = None, solid: list[str] = (), back: list[str] = (),
              resolved: int = 0, unconfirmed: int = 0, revisit: list[str] = (),
              edits: list[Mapping] = (), unlearned: int = 0,
              undated: list[str] = (), studies: bool = True) -> str:
    """The lean /keepfold card, at most 10 lines (UX-7). `domains` are (title, in_progress, solid,
    not_started); `due` the due concept titles, most urgent first; `coming_up` an assessment
    dict with `days`, `solid`, `total`, `more` and an optional `forecast` (recall on its
    `date`, 0..1) or `calibrating` ({n, need} history pairs); `solid`/`back` concept titles
    that reached
    Solid / came back from Needs refresh this week; `revisit` decision ids; `edits` ambient
    contract/profile edits {session, day, pages}, latest first;
    `undated` ids of pending assessments with no date or a past one; without `studies`
    (dashboard.studies) no concept map, Due line or study menu.
    Optional lines show only when non-empty; every item is raw text, escaped here."""
    parts = [f"{t} {GLYPH['learning']} {a} {GLYPH['solid']} {b} {GLYPH['not_started']} {c}"
             for t, a, b, c in domains]
    life = [f"**{head}:** " + _few(items)
            for head, items in (("Projects", projects), ("Open loops", loops),
                                ("From your notes", ideas)) if items]
    lines = ["### Keepfold"]
    if coming_up:
        a = coming_up
        bits = [esc(_label(a)), _when(a["days"])]
        if a.get("total"):
            bits.append(f"{a['solid']} of {a['total']} tested topics solid")
        if a.get("forecast") is not None:  # beside the Solid count, never instead of it
            d = date.fromisoformat(str(a["date"])[:10])
            bits.append(f"forecast recall on {d.day} {d:%b}: {round(100 * a['forecast'])}%")
        elif a.get("calibrating") and a.get("total"):  # why no number yet
            c = a["calibrating"]
            bits.append(f"forecast after {c['need']} checked reviews ({c['n']} so far)"
                        if c["n"] < c["need"] else "forecast still calibrating")  # B5: no skill
        more = f" (+{a['more']} more)" if a.get("more") else ""
        lines.append("**Coming up:** " + " · ".join(bits) + more)
    if due:  # never the raw backlog above a slice (COACH-3)
        tail = (f" +{len(due) - HOME_SHOWN}" if HOME_SHOWN < len(due) <= DUE_SLICE
                else f" · a slice of {DUE_SLICE} is plenty today" if len(due) > DUE_SLICE
                else "")
        due_s = ", ".join(esc(t) for t in due[:HOME_SHOWN]) + tail
    else:
        due_s = "nothing today"
    lately = [*([f"now solid: {_few(solid, ', ')}"] if solid else []),
              *([f"back to solid: {_few(back, ', ')}"] if back else []),
              *([f"{resolved} mistake{'s' * (resolved != 1)} resolved"] if resolved else [])]
    wait = [*([f"{unconfirmed} about-me line{'s' * (unconfirmed != 1)} to confirm"]
              if unconfirmed else []),
            *([f"decisions to revisit: {_few(revisit, ', ', n=FOLLOW_UPS_SHOWN)}"]
              if revisit else []),
            *([f"{len(undated)} test{'s' * (len(undated) != 1)} "
               f"need{'s' * (len(undated) == 1)} a date (or a result): "
               + ", ".join(f"[[{esc(i)}]]" for i in undated[:HOME_SHOWN])] if undated else []),
            *([f"{unlearned} past chat{'s' * (unlearned != 1)} to learn from"]
              if unlearned else [])]
    if edits:
        e = edits[0]
        wait.append(f"{' and '.join(e['pages'])} edited in another chat on {esc(e['day'])} · "
                    f"undo: `keepfold undo {e['session']}`"  # ids checked by the caller
                    + (f" (+{len(edits) - 1} more)" if len(edits) > 1 else ""))
    return "\n".join([
        *lines, *life,
        *(["**Your map:** " + (_few(parts) or "no concepts yet")] if studies else []),
        *([f"**Due:** {due_s} · **Open mistakes:** {open_mistakes}"] if studies else []),
        *(["**Lately:** " + " · ".join(lately)] if lately else []),
        *(["**Waiting for you:** " + " · ".join(wait)] if wait else []),
        "**What would you like to do?** recall something · save this chat · a project · "
        "open the graph · today's plan"
        + (" · study: learn a topic, review what's due, a 10-question sweep" if studies else "")])


def start_card(*, mode: str, today: list[dict], assessments: list[dict],
               open_mistakes: list[tuple[str, int]], date: str,
               deadlines: list[dict] = ()) -> str:
    """Plan steps carry no day or date (v8: a plan is an ordered list per subject); only
    assessments and plan deadlines (planner.deadlines) under Coming up have dates."""
    head = ["Keepfold", MODE_LABEL.get(mode, esc(mode))]
    if mode == "sweep" and today:  # dogfood r4 #7: the plan's length, not a promised 10
        head[1] += f" ({len(today)} cold question{'s' if len(today) > 1 else ''})"
    head.append(esc(date))
    lines = ["### " + " · ".join(head)]
    if mode in MODE_HINT:  # no quiz plan: the brief (returned beside the card) and one hint
        return "\n".join([*lines, MODE_HINT[mode]])
    shown = today if mode == "sweep" else today[:PLAN_LINES]  # a sweep is not in Today.md
    if today:
        lines.append(f"**Today's plan** ({len(shown)} of {len(today)})")
        lines += [f"- {_glyph(i)} {esc(i['title'])} · {esc(i.get('why') or '')}".rstrip(" ·")
                  for i in shown]
        if len(today) > len(shown):
            lines.append(f"+{len(today) - len(shown)} more in Today.md")
    elif mode != "mock":  # a mock has no plan; its card keeps assessments and mistakes
        lines.append("**Today's plan:** nothing planned yet")
    unchecked = _unchecked_titles(today)  # the plan's lane: privacy-filtered, 7-day rule
    if unchecked:
        lines.append("**Taught, not yet checked:** " + ", ".join(unchecked))
    coming = _coming(assessments, deadlines)[:COMING_UP]
    if coming:
        lines.append("**Coming up:** " + "; ".join(coming))
    if open_mistakes:
        lines.append("**Open mistakes:** " + ", ".join(
            f"⚑ {esc(t)} ({n}×)" for t, n in open_mistakes[:MISTAKES_SHOWN]))
    return "\n".join(lines)


def _change(c: Mapping) -> str:
    kind, op, target = c.get("kind") or "", c.get("op"), c.get("target")
    if kind == "person":  # V4: session notes are indexed, so never name a private person
        return "changed a people page"
    ref = esc(f"{Vault.KIND_DIRS.get(kind, kind)}/{c.get('id')}")
    if c.get("tool") == "patch":
        if op == "set_field":
            return f"set {ref} {esc(target or '')}"
        if op == "set_topics":
            return f"set topics on {ref}"
        verb = "checked an item in" if op == "check_item" else "patched"
        tail = " (append)" if op == "append_to_section" else ""
        return f"{verb} {ref} § {esc(target or '')}{tail}"
    if c.get("tool") == "split":
        return f"split {ref} into sub-topics ({esc(str(target))} pages moved)"
    if c.get("tool") == "void":
        return f"voided {esc(kind)} {esc(c.get('id'))} ({esc((c.get('reason') or '')[:200])})"
    if c.get("tool") == "journal":
        return "journal line added"
    if c.get("tool") == "add":
        return f"{'adopted' if op == 'adopt' else 'added'} {esc(kind)} {esc(c.get('id'))}"
    return f"{esc(c.get('tool'))} {ref}"


def changed_lines(changes: list[dict]) -> list[str]:
    """One Markdown bullet per distinct vault change, repeats as ×N, capped."""
    seen: dict[str, int] = {}
    for c in changes:
        line = _change(c)
        seen[line] = seen.get(line, 0) + 1
    lines = [f"- {k}" + (f" ×{n}" if n > 1 else "") for k, n in seen.items()]
    if len(lines) > CHANGED_SHOWN:
        lines = lines[:CHANGED_SHOWN] + [f"+{len(lines) - CHANGED_SHOWN} more"]
    return lines


def end_card(*, counts: dict, moved: list[dict], unchecked: list[str], new_mistakes: list[str],
             next_items: list[dict], plan_cleared: bool, duration_min: int,
             changes: list[dict] = (), not_committed: list[str] = ()) -> str:
    """`moved` items are {title, before, after} with state keys; `counts` has graded, logged;
    `not_committed` holds session close's "<path>: <pattern>" entries (files held back)."""
    lines = [f"### Session closed · {duration_min} min · {counts.get('graded', 0)} answers · "
             f"{counts.get('logged', 0)} logged"]
    if moved:
        parts = [f"{esc(m['title'])} {GLYPH.get(m.get('before'), NO_CONCEPT)} → "
                 f"{GLYPH.get(m.get('after'), NO_CONCEPT)} {LABEL.get(m.get('after'), '')}".rstrip()
                 for m in moved[:MOVED_SHOWN]]
        if len(moved) > MOVED_SHOWN:
            parts.append(f"+{len(moved) - MOVED_SHOWN} more")
        lines.append("**Moved:** " + "; ".join(parts))
    else:
        lines.append("**Moved:** nothing changed this time")
    if new_mistakes:
        lines.append("**New mistakes:** " + "; ".join(f"⚑ {esc(t)}" for t in new_mistakes))
    if unchecked:
        lines.append("**Taught, not yet checked:** " + ", ".join(esc(t) for t in unchecked)
                     + " — first in your next plan")
    if changes:
        lines += ["**Changed:**", *changed_lines(changes)]
    types: dict[str, int] = {}
    for c in changes:
        if c.get("tool") == "add" and c.get("kind") == "note" and c.get("op") == "create":
            t = str(c.get("note_type") or "untyped")
            types[t] = types.get(t, 0) + 1
    if types:
        lines.append(f"**New notes this session:** {sum(types.values())} ("
                     + ", ".join(f"{n} {esc(t)}" for t, n in sorted(types.items())) + ")")
    # the pattern holds no ": " (secret_rules.SECRET_RES), so the path is what precedes it
    lines += [f"Not committed: {esc(w.rpartition(': ')[0] or w)} (looks like a key)"
              for w in not_committed]
    if next_items:
        lines.append("**Next:** " + ", ".join(esc(i["title"]) for i in next_items[:NEXT_SHOWN]))
    if plan_cleared:
        lines.append("Done for today ✓")
    return "\n".join(lines)


def today_md(*, today: list[dict], assessments: list[dict], as_of: str,
             cues: Mapping[str, str] | None = None, deadlines: list[dict] = ()) -> str:
    """`cues` maps concept -> last question asked on it (raw); re-check items show it.
    `deadlines` (planner.deadlines) join the assessments under Coming up."""
    cues = cues or {}
    lines = [TODAY_HEADER, f"# Today · {esc(as_of)}", "", "## Plan"]
    for i in today:
        state = i.get("state")
        mark = f"{GLYPH[state]} {LABEL[state]}" if state in GLYPH else NO_CONCEPT
        why = esc(i.get("why") or "")
        # the planner's "more steps" pointer links its track page (a vault id, ID_RE-safe)
        title = f"More steps are in [[{esc(i['more'])}]]" if i.get("more") \
            else esc(i["title"])
        lines.append(f"- {mark} · {title}" + (f" · {why}" if why else ""))
        if i.get("model"):  # a vault id, ID_RE-safe like `more`
            lines.append(f"  - Re-derive [[{esc(i['model'])}]]: approach and complexity in "
                         "2 minutes, no code")
        if i["kind"] in CUE_KINDS and cues.get(i["id"]):
            lines.append("  - Past question (answer in your own words first): "
                         + esc(cues[i["id"]], CUE_CHARS))
    if not today:
        lines.append("Nothing planned yet.")
    unchecked = _unchecked_titles(today)
    if unchecked:
        lines += ["", "## Taught but not checked"] + [f"- {t}" for t in unchecked]
    coming = _coming(assessments, deadlines)
    if coming:
        lines += ["", "## Coming up"] + [f"- {c}" for c in coming]
    lines += ["", "Refresh with /keepfold or `keepfold brief`", ""]
    return "\n".join(lines)


INDEX_KINDS = (("project", "Projects"), ("resource", "Resources"), ("decision", "Decisions"),
               ("problem", "Problems"), ("mistake", "Mistakes"), ("assessment", "Assessments"),
               ("application", "Applications"), ("track", "Tracks"))
NOTE_SECTIONS = (("permanent", "Permanent notes"), ("structure", "Structure notes"))
INDEX_JOURNAL = 30  # latest journal pages listed, newest first


def index_md(notes: list, entries: Mapping, states: Mapping[str, str]) -> str:
    """index.md: non-private notes by kind, concepts domain > area.

    `entries` is Catalog.entries (for titles and grouping), `states` maps concept id to state.
    """
    def line(n, glyph: str = "") -> str:
        label = esc(n.fields.get("summary") or "") or esc(n.fields.get("title") or n.id)
        return f"- {glyph}[[{n.id}]] — {label}"

    def title(id: str) -> str:
        return esc(entries[id].title) if id in entries else esc(id)

    out = [INDEX_HEADER, "# Index"]
    tree: dict[str, dict[str, list]] = {}
    for n in sorted((n for n in notes if n.kind == "concept"), key=lambda n: n.id):
        e = entries.get(n.id)
        dom = e.domain if e else ""
        area = e.parent if e and e.parent and e.parent != dom else ""
        tree.setdefault(dom, {}).setdefault(area, []).append(n)
    if tree:
        out += ["", "## Concepts"]
    for dom, areas in sorted(tree.items()):
        out += ["", f"### {title(dom) if dom else 'No domain'}"]
        for area, cs in sorted(areas.items()):
            if area:
                out += ["", f"#### {title(area)}"]
            out += [line(n, GLYPH.get(states.get(n.id), NO_CONCEPT) + " ") for n in cs]
    wiki = sorted((n for n in notes if n.kind == "note"), key=lambda n: n.id)
    typed = {t for t, _ in NOTE_SECTIONS}
    sections = [(h, [n for n in wiki if n.fields.get("note_type") == t])
                for t, h in NOTE_SECTIONS]
    sections.append(("Other notes", [n for n in wiki if n.fields.get("note_type") not in typed]))
    sections += [(h, sorted((n for n in notes if n.kind == k), key=lambda n: n.id))
                 for k, h in INDEX_KINDS]
    sections.append(("About me", sorted((n for n in notes if n.kind == "me"),
                                        key=lambda n: n.id)))
    sections.append(("Journal", sorted((n for n in notes if n.kind == "journal"),
                                       key=lambda n: n.id, reverse=True)[:INDEX_JOURNAL]))
    for heading, items in sections:
        if items:
            out += ["", f"## {heading}", *[line(n) for n in items]]
    return "\n".join(out) + "\n"
